export function calcStats(speciesId, level) {
  const sp = MONSTERS[speciesId];
  const hp = Math.floor(((sp.base.hp * 2) * level) / 100) + level + 10;
  const atk = Math.floor(((sp.base.atk * 2) * level) / 100) + 5;
  const def = Math.floor(((sp.base.def * 2) * level) / 100) + 5;
  const spd = Math.floor(((sp.base.spd * 2) * level) / 100) + 5;
  return { maxHp: hp, atk, def, spd };
}

export function expForLevel(level) {
  return Math.floor(Math.pow(level, 3) * 0.8);
}

export function createMonster(speciesId, level, forceShiny = false) {
  const sp = MONSTERS[speciesId];
  const stats = calcStats(speciesId, level);
  const moves = [];
  const levels = Object.keys(sp.learnset).map(Number).sort((a, b) => a - b);
  for (const lv of levels) {
    if (lv <= level) {
      for (const mId of sp.learnset[lv]) {
        if (!moves.some((m) => m.id === mId)) {
          moves.push({ id: mId, pp: null });
        }
      }
    }
  }
  const finalMoves = moves.slice(-4);
  const shiny = forceShiny || Math.random() < 1 / 48; // 1/48 so players have a real chance to see one!
  return {
    uid: Math.random().toString(36).slice(2, 10),
    speciesId,
    nickname: sp.name,
    level,
    exp: expForLevel(level),
    nextExp: expForLevel(level + 1),
    hp: stats.maxHp,
    maxHp: stats.maxHp,
    atk: stats.atk,
    def: stats.def,
    spd: stats.spd,
    status: null, // 'PSN' | 'BRN' | 'PAR' | 'SLP'
    sleepTurns: 0,
    shiny,
    moves: finalMoves,
  };
}
